def poly(pts, fill, op=None):
    d = "M" + " L".join(f"{x:g},{y:g}" for x, y in pts) + " Z"
    o = f' fill-opacity="{op}"' if op else ""
    return f'<path d="{d}" fill="{fill}"{o}/>'


def smooth(pts, n=14):
    p = [pts[0]] + list(pts) + [pts[-1]]
    out = []
    for i in range(1, len(p) - 2):
        p0, p1, p2, p3 = p[i - 1], p[i], p[i + 1], p[i + 2]
        for k in range(n):
            t = k / n
            out.append(tuple(
                0.5 * ((2 * p1[j]) + (-p0[j] + p2[j]) * t + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t * t
                       + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * t ** 3) for j in (0, 1)))
    out.append(pts[-1])
    return out


def at(line, frac):
    """Index and point where the line first reaches `frac` of the way up, by height."""
    y0, y1 = line[0][1], line[-1][1]
    target = y0 - frac * (y0 - y1)
    for i in range(1, len(line)):
        a, b = line[i - 1], line[i]
        if b[1] <= target <= a[1]:
            t = 0 if a[1] == b[1] else (a[1] - target) / (a[1] - b[1])
            return i, (a[0] + (b[0] - a[0]) * t, target)
    return len(line) - 1, line[-1]


def cut(line, f0, f1):
    i0, p0 = at(line, f0)
    i1, p1 = at(line, f1)
    return [p0] + line[i0:i1] + [p1]


def d(line):
    return "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in line)


def tomato(x, y, big=True):
    r = 4.4 if big else 3.3
    return (f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}" fill="#FF4F45" stroke="#1C1C1E" stroke-width="1.4"/>'
            f'<ellipse cx="{x:.1f}" cy="{y - r:.1f}" rx="{r * .43:.1f}" ry="{r * .27:.1f}" fill="#34C759"/>')


def jar(x, y):
    return (f'<rect x="{x - 4.5}" y="{y - 4.5}" width="9" height="11" rx="2.2" fill="#FF4F45" stroke="#1C1C1E" stroke-width="1.4"/>'
            f'<rect x="{x - 4}" y="{y - 7.1}" width="8" height="2.6" rx="1.2" fill="#8E8E93"/>')


def widget(p):
    line = smooth(p["trail"])
    f, f_today = p["frac"], p["today_from"]
    _, you = at(line, f)
    top = line[-1]
    s = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 480 232" width="480" height="232" '
         'style="font-family:-apple-system,system-ui,sans-serif">',
         '<clipPath id="sc"><rect x="8" y="8" width="464" height="216" rx="10"/></clipPath>',
         '<rect width="480" height="232" rx="18" fill="#000"/>', '<g clip-path="url(#sc)">']
    s += [poly(*l) for l in p["layers"]]
    s.append('<g fill="none" stroke-linecap="round" stroke-linejoin="round">')
    s.append(f'<path d="{d(line)}" stroke="#1C1C1E" stroke-width="4"/>')
    s.append(f'<path d="{d(cut(line, f, 1))}" stroke="#fff" stroke-opacity=".65" stroke-width="2" stroke-dasharray="2 4"/>')
    s.append(f'<path d="{d(cut(line, 0, f_today))}" stroke="#fff" stroke-opacity=".78" stroke-width="2"/>')
    s.append(f'<path d="{d(cut(line, f_today, f))}" stroke="#FF4F45" stroke-width="2.6"/>')
    s.append('</g>')
    for hx, hy in p.get("huts", []):
        s.append(f'<rect x="{hx - 1.6}" y="{hy - 1.6}" width="3.2" height="3.2" fill="#E5E5EA" stroke="#1C1C1E" stroke-width=".8"/>')
    for mf, big in p["markers"]:
        _, m = at(line, mf)
        s.append(tomato(m[0], m[1], big))
    s.append(f'<path d="M{top[0]:g},{top[1]:g} v-11" stroke="#D1D1D6" stroke-width="1.2"/>'
             f'<path d="M{top[0]:g},{top[1] - 11:g} l10,2.5 l-10,2.5 Z" fill="#64D2FF"/>')
    s.append(f'<circle cx="{you[0]:.1f}" cy="{you[1]:.1f}" r="5" fill="#fff" stroke="#FF4F45" stroke-width="2.6"/>')
    s.append('</g>')
    s.append('<path d="M16,27 L21,18 L24,22.5 L26.5,19.5 L32,27 Z" fill="#fff"/><circle cx="452" cy="24" r="12" fill="#262628"/>'
             '<path d="M448,28 L456,20 M451.5,20 H456 V24.5 M448,23.5 V28 H452.5" stroke="#fff" stroke-opacity=".8" stroke-width="1.3" fill="none" stroke-linecap="round"/>')
    t = 'font-size="12" font-weight="500" fill="#fff" fill-opacity=".6"'
    s.append(f'<text x="38" y="27" font-size="12" font-weight="600" fill="#fff">{p["name"]}</text>')
    s.append(f'<text x="16" y="78" font-size="37" font-weight="700" fill="#fff">{p["climbed"]}'
             '<tspan font-size="14" font-weight="500" fill-opacity=".6" dx="3">m</tspan></text>')
    s.append(f'<text x="16" y="98" {t}>of {p["height"]} m · {round(f * 100)}% up</text>')
    x = 22
    for _ in range(p.get("jars", 0)):
        s.append(jar(x, 114)); x += 14
    for _ in range(p["today"]):
        s.append(tomato(x, 114)); x += 13
    s.append(f'<text x="{x - 2}" y="118" {t}>today</text>')
    s.append(f'<text x="16" y="138" {t}>{p["status"]}</text>')
    lx, ly = p.get("label", (14, -6))
    s.append(f'<text x="{top[0] + lx:g}" y="{top[1] + ly:g}" font-size="12" font-weight="500" fill="#fff" fill-opacity=".5">{p["height"]} m</text>')
    s.append('</svg>')
    return "\n".join(s)


