#!/usr/bin/env python3
# Writes Sources/Pomodorolog/Surfaces/PeakScenes.swift from the drawings in gen.py and fuji.svg.
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen

OUT = os.path.join(HERE, "..", "..", "..", "Sources", "Pomodorolog", "Surfaces", "PeakScenes.swift")


def polys(dstr):
    """Polygons of an absolute M/L/H/V/Z path."""
    out, cur = [], []
    x = y = 0.0
    for cmd, args in re.findall(r"([MLHVZ])([^MLHVZ]*)", dstr):
        n = [float(v) for v in re.findall(r"-?\d+\.?\d*", args)]
        if cmd in "ML":
            for i in range(0, len(n), 2):
                x, y = n[i], n[i + 1]
                cur.append((x, y))
        elif cmd == "H":
            x = n[0]; cur.append((x, y))
        elif cmd == "V":
            y = n[0]; cur.append((x, y))
        elif cmd == "Z":
            out.append(cur); cur = []
    return out


def sample_curve(dstr, n=10):
    """A polyline along an absolute M/C/Q path."""
    pts = []
    for cmd, args in re.findall(r"([MCQ])([^MCQ]*)", dstr):
        v = [float(a) for a in re.findall(r"-?\d+\.?\d*", args)]
        if cmd == "M":
            pts.append((v[0], v[1]))
        elif cmd == "C":
            for i in range(0, len(v), 6):
                p0 = pts[-1]; c1 = v[i:i + 2]; c2 = v[i + 2:i + 4]; p3 = v[i + 4:i + 6]
                for k in range(1, n + 1):
                    t = k / n; u = 1 - t
                    pts.append(tuple(u ** 3 * p0[j] + 3 * u * u * t * c1[j] + 3 * u * t * t * c2[j] + t ** 3 * p3[j] for j in (0, 1)))
        elif cmd == "Q":
            for i in range(0, len(v), 4):
                p0 = pts[-1]; c = v[i:i + 2]; p2 = v[i + 2:i + 4]
                for k in range(1, n + 1):
                    t = k / n; u = 1 - t
                    pts.append(tuple(u * u * p0[j] + 2 * u * t * c[j] + t * t * p2[j] for j in (0, 1)))
    return pts


def fuji():
    svg = open(os.path.join(HERE, "fuji.svg")).read()
    body = svg[svg.index('<g clip-path'):svg.index('<g fill="none"')]
    layers = []
    for d, fill, rest in re.findall(r'<path d="([^"]+)" fill="(#[0-9A-Fa-f]{3,6})"([^>]*)/>', body):
        op = re.search(r'fill-opacity="([\d.]+)"', rest)
        for p in polys(d):
            layers.append((p, fill, float(op.group(1)) if op else 1))
    trail = re.search(r'<path d="(M56,196[^"]+)" stroke="#1C1C1E"', svg).group(1)
    huts = [(300.2, 133.2), (317.8, 117), (325, 106.3), (331, 96.3)]
    return dict(name="Mount Fuji", layers=layers, line=sample_curve(trail), huts=huts, label=(14, -6))


def pts(points):
    return " ".join(f"{x - 8:.1f},{y - 8:.1f}".replace(".0,", ",").removesuffix(".0") for x, y in points)


scenes = {}
for p in gen.PEAKS:
    layers = [(l[0], l[1], l[2] if len(l) > 2 else 1) for l in p["layers"]]
    scenes[p["name"]] = dict(name=p["name"], layers=layers, line=gen.smooth(p["trail"], 8), huts=p.get("huts", []), label=p.get("label", (14, -6)))
scenes["Mount Fuji"] = fuji()
order = ["Ben Nevis", "Mount Fuji", "Mont Blanc", "Kilimanjaro", "Aconcagua", "Everest", "Olympus Mons"]

s = ["""//
//  PeakScenes.swift
//  Pomodorolog
//
//  The picture of each peak on the summit widget: its flat planes from the
//  back to the front, the line its trail follows, and the huts along it.
//  Generated by docs/summit/generator/export_swift.py from the drawings in
//  docs/summit, which were made against photographs; change the drawing and
//  run it again, don't edit the numbers here.
//

import CoreGraphics

extension PeakScenes {
    /// In the order of `Peaks.all`.
    static let all: [PeakSceneArt] = ["""]
for name in order:
    sc = scenes[name]
    s.append(f"        // {name}")
    s.append("        PeakSceneArt(")
    s.append("            planes: [")
    for points, fill, op in sc["layers"]:
        if len(fill) == 4:  # Color(hex:) reads six digits only
            fill = "#" + "".join(c * 2 for c in fill[1:])
        s.append(f'                ("{fill}", {op:g}, "{pts(points)}"),')
    s.append("            ],")
    s.append(f'            trail: "{pts(sc["line"])}",')
    s.append(f'            huts: "{pts(sc["huts"])}",')
    s.append(f'            labelOffset: CGSize(width: {sc["label"][0]}, height: {sc["label"][1]})')
    s.append("        ),")
s.append("    ]\n}\n")
open(OUT, "w").write("\n".join(s))
print("wrote", os.path.normpath(OUT), len(order), "scenes")
